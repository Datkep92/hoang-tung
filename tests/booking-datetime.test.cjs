const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync('index.html', 'utf8');
const scripts = [...html.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)].map(x => x[1]);
const init = scripts.find(x => x.includes("$('date').min") && x.includes("$('date').value"));
assert(init, 'date/time initialization missing');
const statement = init.match(/const today=new Date\(\),pad=n=>[\s\S]*?\$\('time'\)\.value=[^;]+;/);
assert(statement, 'date/time statement missing');
const nodes = {date:{value:'',min:''}, time:{value:''}};
vm.runInNewContext(statement[0], {document:{getElementById:id => nodes[id]}, $:id => nodes[id]});
const d = new Date(), p = n => String(n).padStart(2,'0');
assert.equal(nodes.date.value, [d.getFullYear(), p(d.getMonth()+1), p(d.getDate())].join('-'));
assert.equal(nodes.date.min, nodes.date.value);
assert.equal(nodes.time.value, p(d.getHours()) + ':' + p(d.getMinutes()));
assert(html.includes('class="full booking-datetime"'));
assert(html.includes('#booking .booking-datetime{display:grid;grid-template-columns:repeat(2,minmax(0,1fr))'));
assert(html.includes('id="booking-datetime-tidy"'));
assert(html.includes('#booking .booking-datetime>label{display:flex;flex-direction:column;min-width:0;white-space:nowrap}'));
assert(html.includes('padding-inline:clamp(2px,1.5vw,8px)'));
assert(/<input id="date" lang="en-GB"[^>]*type="date"/.test(html), 'date format locale missing');
assert(!html.includes('Liên hệ để xác nhận giá theo địa chỉ đón/trả.'));
assert(!html.includes('Liên hệ để xác nhận giá theo địa chỉ cụ thể.'));
assert(!html.includes('Contact us to confirm the fare'));
assert(html.includes("money(r[1+Number($('seat').value)]):''"));
assert(html.includes("q.textContent=r?a[0]+money(r[1+Number($('seat').value)]):''"), 'quote fallback still visible');
console.log('PASS: date/time defaults, side-by-side mobile layout, price fallback hidden');
